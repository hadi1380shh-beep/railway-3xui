def clean(s):
    if not isinstance(s, str):
        return s
    for a, b in RULES:
        if a in s:
            s = s.replace(a, b)
    s = s.replace("«公开»", "«آشکار»")
    s = s.replace("  ", " ")
    # حذف «» های ناهمخوان
    out = []
    depth = 0
    for ch in s:
        if ch == "«":
            if depth:
                continue          # تودرتویی که بسته نمی‌شود؛ حذف
            depth += 1
        elif ch == "»":
            if not depth:
                continue          # بستنِ بی‌بازگشت؛ حذف
            depth -= 1
        out.append(ch)
    if depth:
        s2 = "".join(out)
        # اگر بازمانده‌ای بود، پیش از نقطه/ویرگولِ آخر ببند
        for punc in ("؛", ".", "،"):
            if s2.rstrip().endswith(punc):
                i = s2.rstrip().__len__() - s2.rstrip().count(punc)
                break
        idx = max(s2.rfind("؛"), s2.rfind("."), s2.rfind("!"))
        if idx > 0:
            s2 = s2[:idx] + "»" + s2[idx:]
        s = s2
    # اَعرابِ اضافیِ بی‌جا در متن فارسی
    s = re.sub(r"(?<=[\u06F0-\u06FF])[\u064B-\u0652\u0670]", "", s)
    return s


def dump(mod_name, path, header):
    mod = {"ch13x": ch13x, "ch21": ch21}[mod_name]
    ch = mod.CHAPTER
    lines = [header, "", "CHAPTER = dict(",
             "    num=%d, ordinal=%r," % (ch["num"], ch["ordinal"]),
             "    title=%r," % clean(ch["title"]),
             "    intro=%r," % clean(ch["intro"]),
             ")", "", "Q = []", ""]
    for q in mod.Q:
        lines.append("Q.append(dict(")
        lines.append("    num=%d," % q["num"])
        lines.append("    title=%r," % clean(q["title"]))
        lines.append("    body=[")
        for p in q["body"]:
            lines.append("        %r," % clean(p))
        lines.append("    ],")
        lines.append("    quotes=[")
        for ar, tr, sr in q["quotes"]:
            lines.append("        (%r, %r, %r)," % (clean(ar), clean(tr), clean(sr)))
        lines.append("    ],")
        lines.append("    menbar=%r," % clean(q["menbar"]))
        lines.append("))")
        lines.append("")
    open(path, "w", encoding="utf-8").write("\n".join(lines))


